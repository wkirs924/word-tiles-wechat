import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {resolve,join} from 'node:path';
import {createHash} from 'node:crypto';

const root=resolve('.');
const source=join(root,'packages','core','src');
const dest=join(root,'apps','client-cocos','assets','scripts','generated','core');
mkdirSync(dest,{recursive:true});
const hashes={};
for(const name of ['json','rules','setup','scoring','round','session','projection']) {
  const src=readFileSync(join(source,`${name}.ts`),'utf8');
  const body=src.replaceAll(/(from\s+['"]\.\/[A-Za-z-]+)\.ts(['"])/g,'$1$2');
  const output=join(dest,`${name}.ts`);
  writeFileSync(output,`// Generated by scripts/sync-cocos-core.mjs from packages/core/src/${name}.ts. Do not edit.\n${body}`);
  hashes[name]=createHash('sha256').update(src).digest('hex');
}
const catalog=JSON.parse(readFileSync(join(root,'reference','godot','content','catalog.json'),'utf8'));
const presets=catalog.deck_presets.map(({id,title,deck})=>({id,title,deck}));
if(presets.length!==2||presets.some(p=>p.deck.reduce((n,e)=>n+e.copies,0)!==136))throw Error('INVALID_REFERENCE_DECKS');
const content=join(root,'apps','client-cocos','assets','scripts','generated','deckPresets.ts');
writeFileSync(content,`// Generated from the pinned reference/godot/content/catalog.json. Do not edit.\nexport const DECK_PRESETS = ${JSON.stringify(presets,null,2)} as const;\n`);
const previewSource=readFileSync(join(root,'packages','preview','src','local-table.ts'),'utf8');
const previewBody=previewSource.replaceAll("'../../core/src/session.ts'","'./core/session'")
  .replaceAll("'../../core/src/projection.ts'","'./core/projection'")
  .replaceAll("'../../core/src/setup.ts'","'./core/setup'")
  .replaceAll("'../../core/src/rules.ts'","'./core/rules'");
writeFileSync(join(root,'apps','client-cocos','assets','scripts','generated','LocalTable.ts'),`// Generated from packages/preview/src/local-table.ts. Do not edit.\n${previewBody}`);
writeFileSync(join(root,'apps','client-cocos','generated-hashes.json'),JSON.stringify({core:hashes,reference_catalog_sha256:createHash('sha256').update(readFileSync(join(root,'reference','godot','content','catalog.json'))).digest('hex')},null,2)+'\n');
console.log(`Synced ${Object.keys(hashes).length} core modules and ${presets.length} decks into Cocos assets.`);
