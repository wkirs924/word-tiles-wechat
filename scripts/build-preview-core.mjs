// Bundles the TypeScript rule core into a plain script that both the browser preview and
// the WeChat mini-game runtime can load. It uses Node's type stripping and a tiny
// CommonJS wrapper: no npm dependencies, no duplicated rule source.
import {readFileSync, writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {stripTypeScriptTypes} from 'node:module';

const root = resolve(import.meta.dirname, '..');
const output = resolve(root, 'apps', 'wechat-preview', 'core.bundle.js');

const MODULES = [
  'packages/core/src/json.ts',
  'packages/core/src/rules.ts',
  'packages/core/src/setup.ts',
  'packages/core/src/scoring.ts',
  'packages/core/src/round.ts',
  'packages/core/src/session.ts',
  'packages/core/src/projection.ts',
  'packages/content/src/search.ts',
  'packages/preview/src/local-table.ts',
];
const ENTRIES = [
  'packages/preview/src/local-table.ts',
  'packages/content/src/search.ts',
];
const PICKS = [
  ['packages/preview/src/local-table.ts', ['LocalTable', 'SEATS']],
  ['packages/content/src/search.ts', ['rankMemes']],
  ['packages/core/src/setup.ts', ['expandDeck']],
  ['packages/core/src/projection.ts', ['playerView', 'playerEvents']],
  ['packages/core/src/session.ts', ['createSession', 'reduceSession']],
  ['packages/core/src/rules.ts', ['sentenceScore', 'defaults']],
];
function transform(code, id) {
  const exported = [];
  code = code.replace(
    /^import\s+(?:[\w$]+\s*,\s*)?\{([^}]*)\}\s*from\s*['"]([^'"]+)['"];?[ \t]*$/gm,
    (match, names, spec) => {
      const parts = names
        .split(',')
        .map(entry => entry.trim())
        .filter(Boolean)
        .map(entry => {
          const alias = entry.split(/\s+as\s+/);
          return alias[1] ? `${alias[0].trim()}: ${alias[1].trim()}` : entry.trim();
        });
      return parts.length ? `const {${parts.join(', ')}} = require(${JSON.stringify(spec)});` : '';
    },
  );
  code = code.replace(
    /^import\s+([A-Za-z_$][\w$]*)\s+from\s*['"]([^'"]+)['"];?[ \t]*$/gm,
    (match, name, spec) => `const ${name} = require(${JSON.stringify(spec)}).default;`,
  );
  code = code.replace(/^export\s+(function|class|const|let|var)\s+([A-Za-z_$][\w$]*)/gm, (match, kind, name) => {
    exported.push(name);
    return `${kind} ${name}`;
  });
  code = code.replace(/^export\s*\{([^}]*)\};?[ \t]*$/gm, (match, names) => {
    names
      .split(',')
      .map(entry => entry.trim())
      .filter(Boolean)
      .forEach(entry => {
        const alias = entry.split(/\s+as\s+/);
        exported.push(alias[1] ? alias[1].trim() : entry);
      });
    return '';
  });
  if (/^\s*import\s/m.test(code)) throw new Error(`unhandled import in ${id}`);
  if (/^\s*export\s/m.test(code)) throw new Error(`unhandled export in ${id}`);
  return {code, exported};
}

const definitions = MODULES.map(id => {
  const source = readFileSync(resolve(root, id), 'utf8');
  const stripped = stripTypeScriptTypes(source, {mode: 'strip', sourceUrl: id});
  const {code, exported} = transform(stripped, id);
  return {id, code, exported};
});

let out = '';
out += '// Generated by scripts/build-preview-core.mjs from packages/core, packages/content and packages/preview.\n';
out += '// Do not edit by hand. Rebuild with: node scripts/build-preview-core.mjs\n';
out += '(function (root) {\n';
out += "'use strict';\n";
out += 'var __mods = {};\nvar __defs = {};\n';
for (const definition of definitions) {
  out += `__mods[${JSON.stringify(definition.id)}] = function (module, exports, require, __export) {\n`;
  out += definition.code;
  out += `\n__export(exports, {${definition.exported.join(', ')}});\n};\n`;
}
out += `
function __resolve(from, spec) {
  var parts = from.split('/');
  parts.pop();
  var bits = spec.split('/');
  for (var i = 0; i < bits.length; i++) {
    if (bits[i] === '.' || bits[i] === '') continue;
    if (bits[i] === '..') parts.pop();
    else parts.push(bits[i]);
  }
  return parts.join('/');
}
function __require(id) {
  if (__defs[id]) return __defs[id].exports;
  if (!__mods[id]) throw new Error('Unknown bundled module: ' + id);
  var def = {exports: {}};
  __defs[id] = def;
  __mods[id](def, def.exports, function (spec) { return __require(__resolve(id, spec)); }, __export);
  return def.exports;
}
function __export(exports, names) {
  for (var key in names) exports[key] = names[key];
}
`;
for (const entry of ENTRIES) out += `__require(${JSON.stringify(entry)});\n`;
out += 'var core = {};\n';
out += 'function __pick(moduleId, names) {\n';
out += "  var source = __defs[moduleId].exports;\n";
out += '  for (var i = 0; i < names.length; i++) core[names[i]] = source[names[i]];\n';
out += '}\n';
for (const [id, names] of PICKS) out += `__pick(${JSON.stringify(id)}, ${JSON.stringify(names)});\n`;
out += 'root.WordTilesCore = core;\n';
out += "if (typeof module !== 'undefined' && module.exports) module.exports = core;\n";
out += "})(typeof globalThis !== 'undefined' ? globalThis : this);\n";

writeFileSync(output, out);
const size = out.length;
console.log(`wrote ${output} (${size} bytes, ${definitions.length} modules)`);
